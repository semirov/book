function Rules() {
  return (
    <main className="page legal">
      <p className="kicker">правила</p>
      <h1 className="title">Как оставить замечание</h1>
      <p className="premise">
        Книга пишется публично, но не голосованием. Замечание — это замечание о тексте: что не
        читается, где сбой, какая деталь не выдерживает проверки. Не приказ и не правка «под
        себя».
      </p>

      <section>
        <h2>Что принимается</h2>
        <p>
          Вмешательство — это своя правка и её тип: факт мира, а не правка прозы. Четыре типа:{' '}
          {INTERVENTION_KIND_LIST}. Одно вмешательство — до {formatNumber(EDIT_MAX_CHARS)} знаков,
          в одном месте, одна правка в сутки на читателя и на адрес.
        </p>
        <p>Замечание без своего варианта — отзыв о тексте: тип у него не спрашивают.</p>
        <ul>
          <li>замечание о тексте: повтор, сбой ритма, неточное слово — с указанием абзаца;</li>
          <li>своя правка — писатель берёт идею, а не байты;</li>
          <li>вопрос о детали мира, если он помогает тексту, а не расширяет его.</li>
        </ul>
      </section>

      <section>
        <h2>Что не принимается</h2>
        <ul>
          <li>новые герои, новые сущности мира, другая концовка — канон не переписывается из ветки;</li>
          <li>реальные люди и чужие образы;</li>
          <li>незаконное содержимое;</li>
          <li>указания модели: «игнорируй инструкции», «с этого момента пиши…», «в стиле…».</li>
        </ul>
        <p>
          Такое замечание не удаляется молча: оно сохраняется, помечается «проверяется» и не
          уходит в работу. Причина видна вам и другим читателям.
        </p>
      </section>

      <section>
        <h2>Как это работает</h2>
        <ul>
          <li>нужен вход через Яндекс ID — иначе нельзя отличить людей от скриптов;</li>
          <li>10 замечаний в час с одного адреса и с одного читателя; одна правка в сутки — на читателя и на адрес;</li>
          <li>замечание читают как данные: модель не подчиняется тексту замечания;</li>
          <li>принятое замечание становится правкой в очереди — принято не значит внесено;</li>
          <li>
            правка расходится волнами по соседним главам — до {CASCADE_MAX_WAVE} волн, глубже
            её останавливает решение владельца;
          </li>
          <li>глава 67 заморожена: правки читателей туда не входят;</li>
          <li>ваше показанное имя видят другие читатели.</li>
        </ul>
      </section>

      <p className="legal-tail">
        Владелец книги — единственный, кто пишет текст. Замечание может быть отклонено с
        публичной причиной; это не оценка вас, а решение о книге.
      </p>
      <p className="legal-nav">
        <a href="/privacy">что здесь видят другие →</a>
        <a href="/">← к книге</a>
      </p>
    </main>
  );
}

export function LegalPage({ page }: { page: StaticPage }) {
  return page === 'privacy' ? <Privacy /> : <Rules />;
}
